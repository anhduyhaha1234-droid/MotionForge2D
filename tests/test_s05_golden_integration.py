def _ffmpeg_available() -> bool:
    try:
        from app.services.ffmpeg_utils import find_ffprobe

        find_ffprobe()
        return shutil.which("ffmpeg") is not None
    except Exception:
        return False


def _make_video(
    path: Path,
    *,
    duration: float = 1.0,
    fps: int = 30,
    color: str = "blue",
) -> Path | None:
    """Create a CFR synthetic MP4/H.264 clip (static color)."""
    ffmpeg = shutil.which("ffmpeg") or "ffmpeg"
    path.parent.mkdir(parents=True, exist_ok=True)
    cmd = [
        ffmpeg,
        "-y",
        "-f",
        "lavfi",
        "-i",
        f"color=c={color}:duration={duration}:size=320x240:rate={fps}",
        "-c:v",
        "libx264",
        "-preset",
        "ultrafast",
        "-crf",
        "28",
        "-pix_fmt",
        "yuv420p",
        str(path),
    ]
    result = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
    if result.returncode != 0:
        return None
    return path


def _make_cut_video(path: Path, *, fps: int = 30, rate: str | None = None) -> Path | None:
    """A 2s/60-frame clip with ONE hard cut at frame ``round(1s * fps)``:
    blue (1s) → red (1s), scene score ~1.0, zero motion noise."""
    ffmpeg = shutil.which("ffmpeg") or "ffmpeg"
    path.parent.mkdir(parents=True, exist_ok=True)
    rate_arg = rate or str(fps)
    cmd = [
        ffmpeg,
        "-y",
        "-f",
        "lavfi",
        "-i",
        f"color=c=blue:duration=1.0:size=320x240:rate={rate_arg}",
        "-f",
        "lavfi",
        "-i",
        f"color=c=red:duration=1.0:size=320x240:rate={rate_arg}",
        "-filter_complex",
        "[0:v][1:v]concat=n=2:v=1:a=0[v]",
        "-map",
        "[v]",
        "-c:v",
        "libx264",
        "-preset",
        "ultrafast",
        "-crf",
        "28",
        "-pix_fmt",
        "yuv420p",
        str(path),
    ]
    result = subprocess.run(cmd, capture_output=True, text=True, timeout=60)
    if result.returncode != 0:
        return None
    return path


def _make_vfr_cut_video(tmp_path: Path, name: str = "vfr.mp4") -> Path | None:
    """A real VFR MP4 with one hard cut: a 30fps blue segment + a 25fps red
    segment concatenated with ``-c copy`` → ``r_frame_rate != avg_frame_rate``
    (genuinely VFR) and a hard color change at the segment boundary."""
    ffmpeg = shutil.which("ffmpeg") or "ffmpeg"
    seg1 = tmp_path / "seg30.mp4"
    seg2 = tmp_path / "seg25.mp4"
    for seg, fps, color in ((seg1, 30, "blue"), (seg2, 25, "red")):
        made = _make_video(seg, duration=1.0, fps=fps, color=color)
        assert made is not None, "ffmpeg failed to create a VFR segment"
    lst = tmp_path / "concat.txt"
    lst.write_text(f"file '{seg1.as_posix()}'\nfile '{seg2.as_posix()}'\n", encoding="utf-8")
    out = tmp_path / name
    result = subprocess.run(
        [
            ffmpeg,
            "-y",
            "-f",
            "concat",
            "-safe",
            "0",
            "-i",
            str(lst),
            "-c",
            "copy",
            "-movflags",
            "+faststart",
            str(out),
        ],
        capture_output=True,
        text=True,
        timeout=60,
    )
    if result.returncode != 0:
        pytest.skip("ffmpeg concat failed to create the VFR fixture")
    probe = video_import.probe_source(out)
    video = probe["video_stream"]
    if video["r_frame_rate"] == video["avg_frame_rate"]:
        pytest.skip("concat output is not genuinely VFR on this ffmpeg build")
    return out


