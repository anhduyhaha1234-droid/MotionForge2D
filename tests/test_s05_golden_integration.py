def _run_job(worker: DurableWorker) -> None:
    worker.run_once()


def _job_state(session_factory, job_id: str) -> str:
    with session_factory() as s:
        return JobRepository(s).get_job(job_id).state


def _job_error(session_factory, job_id: str) -> dict | None:
    with session_factory() as s:
        return JobRepository(s).get_job(job_id).error


def _scene_rows(session_factory, video_item_id: str) -> list[Scene]:
    with session_factory() as s:
        return list(
            s.scalars(
                select(Scene).where(Scene.video_item_id == video_item_id).order_by(Scene.position)
            ).all()
        )


def _staging_files(managed_root: Path) -> list[Path]:
    staging = managed_root / "staging"
    if not staging.is_dir():
        return []
    return [p for p in staging.rglob("*") if p.is_file()]


def _step_checkpoint(session_factory, job_id: str) -> dict:
    with session_factory() as s:
        repo = JobRepository(s)
        step_row = s.get(JobStep, repo.list_steps(job_id)[0].id)
        return json.loads(step_row.checkpoint_json or "{}")


def _artifact_sha_size(path: Path) -> tuple[str, int]:
    return hashlib.sha256(path.read_bytes()).hexdigest(), path.stat().st_size


def _ready_video_artifacts(session_factory, workspace_id: str) -> list[Artifact]:
    with session_factory() as s:
        return list(
            s.scalars(
                select(Artifact)
                .where(
                    Artifact.workspace_id == workspace_id,
                    Artifact.kind == "video",
                    Artifact.state == "ready",
                )
                .order_by(Artifact.relative_path)
            ).all()
        )


def _owner_purposes(session_factory, artifact_id: str) -> set[str]:
    with session_factory() as s:
        return set(
            s.scalars(
                select(ArtifactOwner.purpose).where(ArtifactOwner.artifact_id == artifact_id)
            ).all()
        )


def _api_status(client, job_id: str) -> dict:
    resp = client.get(f"/api/jobs/{job_id}")
    assert resp.status_code == 200, f"GET /api/jobs/{job_id} → {resp.status_code}"
    return resp.json()


# ── AC1: CFR golden path ─────────────────────────────────────────────────────


def test_golden_cfr_full_pipeline_api_state_completed(
    worker, session_factory, ws, video_item, cfr_cut_video, managed_root, api_client
) -> None:
    """CFR golden: import → proxy → scene detection, all jobs `completed`
    through the real job API (the S05-T05 UI surface), VideoItem probe
    columns written, canonical scene rows committed."""
    # 1. Managed import (S05-T02)
    import_job_id, source_artifact_id = _import_source(
        session_factory, worker, ws, video_item, cfr_cut_video, managed_root
    )
    # 2. Canonical timebase + proxy (S05-T03)
    proxy_job_id, proxy_artifact_id = _generate_proxy(
        session_factory, worker, ws, video_item, source_artifact_id, managed_root
    )
    # 3. Scene detection (S05-T04) consuming the proxy
    result = _submit_scene_detection(
        session_factory,
        ws,
        video_item,
        source_artifact_id,
        managed_root,
        proxy_artifact_id=proxy_artifact_id,
    )
    scene_job_id = result.job_id
    _run_job(worker)

    # UI/API state: the exact endpoint the Import/Analyze UI polls.
    import_info = _api_status(api_client, import_job_id)
    proxy_info = _api_status(api_client, proxy_job_id)
    scene_info = _api_status(api_client, scene_job_id)
    assert import_info["status"] == "completed"
    assert import_info["job_type"] == JOB_TYPE_ANALYZE_MEDIA
    assert proxy_info["status"] == "completed"
    assert proxy_info["job_type"] == JOB_TYPE_GENERATE_PROXY
    assert scene_info["status"] == "completed"
    assert scene_info["job_type"] == JOB_TYPE_ANALYZE_MEDIA
    # The scene-detect handler publishes real progress (10 → 60 → 100).
    assert scene_info["progress"] == 100.0

    # VideoItem probe columns persisted by the import publication txn.
    with session_factory() as s:
        item = s.get(VideoItem, video_item.id)
        assert item.duration_ms == 2000
        assert item.width == 320
        assert item.height == 240
        assert (item.fps_num, item.fps_den) == (30, 1)
        assert item.source_artifact_id == source_artifact_id

    # Canonical scene rows (30fps CFR: cut at frame 30 → t=1.000s exactly).
    rows = _scene_rows(session_factory, video_item.id)
    assert len(rows) == 2
    assert [r.position for r in rows] == [0, 1]
    assert [(r.start_frame, r.end_frame) for r in rows] == [(0, 29), (30, 59)]
    assert [(r.start_time_ms, r.end_time_ms) for r in rows] == [(0, 999), (1000, 1999)]
    assert all(r.status == "pending" for r in rows)
    assert all(r.revision == 1 for r in rows)
    assert all(r.legacy_scene_id is None for r in rows)

    # The detection consumed the proxy artifact (golden proxy path).
    cp = _step_checkpoint(session_factory, scene_job_id)
    assert cp["input"]["kind"] == "proxy"
    assert cp["input"]["artifact_id"] == proxy_artifact_id
    assert _staging_files(managed_root) == []


def test_golden_vfr_full_pipeline_exact_rational(
    worker, session_factory, ws, video_item, vfr_cut_video, managed_root, api_client
) -> None:
    """VFR golden: the same pipeline on a real VFR fixture. The import
    classifies VFR; the canonical grid is the exact avg_frame_rate; the
    proxy resamples onto that grid; every scene row recomputes exactly from
    the persisted rational timebase payload."""
    # 1. Import — checkpoint records the real VFR classification.
    import_job_id, source_artifact_id = _import_source(
        session_factory, worker, ws, video_item, vfr_cut_video, managed_root
    )
    import_cp = _step_checkpoint(session_factory, import_job_id)
    src_video = import_cp["probe"]["video_stream"]
    assert src_video["fps_classification"] == "VFR"
    assert src_video["r_frame_rate"] != src_video["avg_frame_rate"]
    avg_num = int(src_video["avg_frame_rate"]["num"])
    avg_den = int(src_video["avg_frame_rate"]["den"])
    assert avg_num > 0 and avg_den > 0

    # 2. Proxy — resampled onto the canonical avg_frame_rate grid.
    proxy_job_id, proxy_artifact_id = _generate_proxy(
        session_factory, worker, ws, video_item, source_artifact_id, managed_root
    )
    proxy_cp = _step_checkpoint(session_factory, proxy_job_id)
    proxy_tb = CanonicalTimebase.from_json(proxy_cp["timebase"])
    assert (proxy_tb.fps_num, proxy_tb.fps_den) == (avg_num, avg_den)

    # 3. Scene detection on the proxy.
    result = _submit_scene_detection(
        session_factory,
        ws,
        video_item,
        source_artifact_id,
        managed_root,
        proxy_artifact_id=proxy_artifact_id,
    )
    scene_job_id = result.job_id
    _run_job(worker)

    # API state completed for all three jobs.
    assert _api_status(api_client, import_job_id)["status"] == "completed"
    assert _api_status(api_client, proxy_job_id)["status"] == "completed"
    assert _api_status(api_client, scene_job_id)["status"] == "completed"
    assert _api_status(api_client, scene_job_id)["progress"] == 100.0

    # Every row recomputes exactly from the persisted rational payload —
