def register_reference_asset_handler(worker: Any) -> None:
    """Register the durable handler + fail-closed output validator."""
    worker.register_handler(
        JOB_TYPE_REFERENCE_ASSET,
        run_reference_asset_job,
        declared_outputs=None,
        output_validator=validate_reference_asset_outputs,
        resource_class="gpu",
    )


@dataclass(frozen=True)
class ReferenceAssetSubmitResult:
    """Outcome of an intent registration (no engine work happened yet)."""

    job: Any
    content_key: str
    reference_key: str
    view: str
    role: str
    duplicate: bool


def _build_manifest(
    *,
    workspace_id: str,
    character_id: str,
    version_id: str,
    reference_key: str,
    view_prompt: str,
    source_reference_key: str,
    source_artifact_id: str,
    source_sha256: str,
    source_size_bytes: int,
    style_version: str | None,
    seed: int | None,
    graph_file_sha256: str,
) -> dict[str, Any]:
    manifest: dict[str, Any] = {
        "schema_version": 1,
        "intent": "reference_asset",
        "workspace_id": workspace_id,
        "character_id": character_id,
        "version_id": version_id,
        "reference_key": reference_key,
        "source_reference_key": source_reference_key,
        "source_artifact_id": source_artifact_id,
        "source_sha256": source_sha256,
        "source_size_bytes": int(source_size_bytes),
        "view_prompt": view_prompt,
        "style_version": style_version,
        "graph_file_sha256": graph_file_sha256,
        "purpose": "artwork",
    }
    if seed is not None:
        manifest["seed"] = int(seed)
    return manifest


def submit_reference_asset_job(
    *,
    job_service: Any,
    workspace_id: str,
    character_id: str,
    version_id: str,
    reference_key: str,
    view_prompt: str,
    source_reference_key: str | None = None,
    style_version: str | None = None,
    seed: int | None = None,
    idempotency_key: str | None = None,
    input_generation: str | None = None,
) -> ReferenceAssetSubmitResult:
    """Validate the live draft pack and register ONE durable job intent.

    No engine work, no library writes: the returned Job is queued and the
    worker performs the run.
    """
    session_factory = getattr(job_service, "session_factory", None)
    if session_factory is None:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.REQUEST_INVALID, "job service exposes no session factory"
        )
    managed_root = Path(job_service.managed_root)
    view, role = parse_target_key(reference_key)
    source_key = source_reference_key or DEFAULT_SOURCE_REFERENCE_KEY
    if source_key == reference_key:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.REQUEST_INVALID,
            "source and target reference keys are identical",
        )
    with session_factory() as session:
        repo = CharacterRepository(session, storage_root=managed_root)
        try:
            version = repo.get_pack_version(version_id, workspace_id)
        except PackVersionNotFoundError as exc:
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.VERSION_NOT_FOUND,
                "pack version not found in this workspace",
                details={"version_id": version_id},
            ) from exc
        if str(version.status) != "draft":
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.VERSION_NOT_DRAFT,
                "the pack version is not a draft; published versions are immutable",
                details={"status": str(version.status)},
            )
        present = {str(a.pose_slot) for a in version.assets}
        if reference_key in present:
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.TARGET_KEY_PRESENT,
                "the target reference key already carries an asset",
                details={"reference_key": reference_key, "present": sorted(present)},
            )
        source_asset = next(
            (a for a in version.assets if str(a.pose_slot) == source_key), None
        )
        if source_asset is None:
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.SOURCE_REFERENCE_MISSING,
                "the source identity reference is not attached to the version",
                details={"source_reference_key": source_key, "present": sorted(present)},
            )
        try:
            _asset, path, _mime = repo.resolve_asset_content(
                character_id=character_id,
                version_id=version_id,
                asset_id=str(source_asset.id),
                workspace_id=workspace_id,
            )
        except Exception as exc:
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.SOURCE_REFERENCE_MISSING,
                f"source reference bytes are not serviceable: {type(exc).__name__}",
                details={"source_reference_key": source_key},
            ) from exc
        data = Path(path).read_bytes()
    source_sha256 = _sha256_bytes(data)
    _document, graph_manifest = load_graph_documents()
    graph_file_sha256 = str((graph_manifest.get("workflow") or {}).get("graph_file_sha256") or "")
    manifest = _build_manifest(
        workspace_id=workspace_id,
        character_id=character_id,
        version_id=version_id,
        reference_key=reference_key,
        view_prompt=view_prompt,
        source_reference_key=source_key,
        source_artifact_id=str(source_asset.id),
        source_sha256=source_sha256,
        source_size_bytes=len(data),
        style_version=style_version,
        seed=seed,
        graph_file_sha256=graph_file_sha256,
    )
    plan = reference_asset_plan(manifest)
    manifest["content_key"] = plan.content_key
    digest = plan.content_key.split(":", 1)[-1][:40]
    key = idempotency_key or f"reference_asset:{version_id}:{digest}"
    duplicate = False
    try:
        info = job_service.create_job(
            JOB_TYPE_REFERENCE_ASSET,
            manifest,
            workspace_id=workspace_id,
            owner_type="character",
            owner_id=character_id,
            idempotency_key=key,
            input_generation=input_generation,
            max_attempts=DEFAULT_MAX_ATTEMPTS,
        )
    except IdempotencyKeyInUse as exc:
        existing = job_service.get_job(str(exc.job_id or ""))
        if existing is None:
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.IDEMPOTENCY_CONFLICT,
                "an active job already holds this intent but is not readable",
                details={"job_id": exc.job_id},
            ) from exc
        info = existing
        duplicate = True
    return ReferenceAssetSubmitResult(
        job=info,
        content_key=plan.content_key,
        reference_key=reference_key,
        view=view,
        role=role,
        duplicate=duplicate,
    )


def resubmit_reference_asset_job(
    *, job_service: Any, job_id: str, input_generation: str | None = None
) -> ReferenceAssetSubmitResult:
    """Retry a terminal reference-asset job as a NEW generation (receipt replayed)."""
    session_factory = getattr(job_service, "session_factory", None)
    if session_factory is None:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.REQUEST_INVALID, "job service exposes no session factory"
        )
    with session_factory() as session:
        row = session.get(Job, job_id)
        if row is None:
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.JOB_NOT_FOUND,
                f"no job {job_id}",
                details={"job_id": job_id},
            )
        if str(row.job_type) != JOB_TYPE_REFERENCE_ASSET:
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.REQUEST_INVALID,
                "the job is not a reference-asset job",
                details={"job_type": str(row.job_type)},
            )
        if str(row.state) not in TERMINAL_STATES:
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.JOB_NOT_RETRYABLE,
                "only a terminal reference-asset job can be retried",
                details={"state": str(row.state)},
            )
        raw_manifest = row.input_manifest_json
        manifest = raw_manifest if isinstance(raw_manifest, dict) else parse_json(raw_manifest, {})
        workspace_id = str(row.workspace_id)
        owner_type = str(row.owner_type)
        owner_id = str(row.owner_id)
        key = str(row.idempotency_key or "")
    if not isinstance(manifest, dict) or not manifest:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.RECEIPT_INCOMPLETE, "the job carries no durable manifest"
        )
    generation = input_generation or f"retry-{uuid.uuid4().hex[:8]}"
    # A terminal predecessor keeps its idempotency key under the partial unique
    # index, so a fresh logical run gets a NEW key that carries the generation.
    retry_key = f"{key}:{generation}" if key else None
    info = job_service.create_job(
        JOB_TYPE_REFERENCE_ASSET,
        manifest,
        workspace_id=workspace_id,
        owner_type=owner_type,
        owner_id=owner_id,
        idempotency_key=retry_key,
        input_generation=generation,
        max_attempts=DEFAULT_MAX_ATTEMPTS,
    )
    plan = reference_asset_plan(manifest)
    return ReferenceAssetSubmitResult(
        job=info,
        content_key=plan.content_key,
        reference_key=plan.reference_key,
        view=plan.view,
        role=plan.role,
        duplicate=False,
    )
