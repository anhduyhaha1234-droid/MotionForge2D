def _engine_model_bindings(graph_models: Any) -> tuple[dict[str, Any], list[Any]]:
    models = list(graph_models or [])
    primary: dict[str, Any] = {}
    auxiliary: list[dict[str, Any]] = []
    for entry in models:
        if not isinstance(entry, dict) or not entry.get("sha256"):
            continue
        binding = {
            "model_id": (
                Path(str(entry.get("file") or "")).stem or str(entry.get("role") or "model")
            ),
            "revision": None,
            "file": {"algorithm": "sha256", "scope": "full_file", "value": str(entry["sha256"])},
            "precision": "not_recorded",
            "size_bytes": int(entry.get("bytes") or 0),
        }
        if str(entry.get("role")) == "diffusion_models" and not primary:
            binding["precision"] = "fp8"
            binding["model_id"] = str(entry.get("file") or "model").replace(".safetensors", "")
            primary = binding
        else:
            auxiliary.append(binding)
    return primary, auxiliary


