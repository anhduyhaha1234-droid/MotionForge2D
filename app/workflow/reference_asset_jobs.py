"""MF-END-09 — durable reference-asset generation jobs (graph G1 → managed library).

One outcome: an API/UI submit registers ONE durable Job intent; the existing
``DurableWorker`` drives it through the shared ``ComfyShotEngine`` authority
(MF-END-18: epoch/lease/gate/reservation, one POST per attempt) over the
reference-asset image graph (MF-END-08: ``app/media_workflows/reference_asset_v1.json``),
and the generated bytes are saved back into the SAME draft pack version as a
ready managed artifact + ``character_asset`` row through the existing authored
reference-artwork ingest (MF-END-03).  The pack is never published here.

Design facts (all fail-closed, each with a typed refusal code):

* **submit is an intent** — :func:`submit_reference_asset_job` validates the
  live draft version, resolves the source identity reference and the target
  ``<view>@<role>`` key, computes the content key, and inserts a durable Job.
  It performs NO engine work and writes no library bytes.
* **content identity** — the cache key is sha256 over
  ``workspace/character/version/reference key/source sha/style/graph file
  sha/prompt/seed/canvas/...`` (:func:`reference_asset_content_key`).  Missing
  one view therefore produces a key for exactly that view; other views are
  never touched (they are not part of any submitted manifest).
* **durable receipt** — ``<managed_root>/reference_asset_jobs/<key>.json``
  records ``submitted`` BEFORE the engine POST and ``completed`` only after the
  library ingest committed.  A retry that finds a ``completed`` receipt replays
  the staged artifact with **0 engine POST**; a retry that finds a non-terminal
  receipt re-drives the engine with the RECORDED attempt identity (the package's
  durable replay: 0 POST when the attempt is terminal on the server) and
  otherwise refuses typed — a second blind POST is never sent.
* **no fixture fallback** — when the pinned engine dependency or the engine
  itself is unavailable, the run refuses typed (``engine_unavailable``); there
  is no synthetic image, no placeholder row, no "test mode" in the production
  path.  Tests inject a fake HTTP transport at the process boundary only.
* **draft-only writes** — the version is re-checked inside the handler and again
  inside the ingest; a published/archived version refuses every write, and the
  target key must be absent (a present key is somebody else's asset).

Disclosed conventions (open points for the reviewer):

* ``<managed_root>/media_engine/comfy_shot_engine/runtime/input`` is the
  app-side staged-input directory, matching MF-END-08's isolation recipe (own
  base-directory with ``input/output/temp/user`` under the managed root).  The
  server launch itself stays outside this module.
* The engine binding is built from the frozen DTO example
  (:data:`app.schemas.shot_reskin.FROZEN_EXAMPLES`) with explicit overrides
  (identity/source/cast/graph/output contract) because the accepted contract
  shape is video-shot shaped; every overridden field is listed here.
"""

