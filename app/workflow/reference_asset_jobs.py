@dataclass(frozen=True)
class _LibraryState:
    source_path: Path
    source_bytes: bytes
    target_asset_id: str | None
    identity_refs: tuple[dict[str, Any], ...]


def _assert_library_state(
    ctx: WorkerContext, plan: ReferenceAssetPlan, managed_root: Path, receipt: dict[str, Any] | None
) -> _LibraryState:
    if ctx.session_factory is None:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.REQUEST_INVALID,
            "the worker context carries no session factory; refusing to run unvalidated",
        )
    with ctx.session_factory() as session:
        repo = CharacterRepository(session, storage_root=managed_root)
        try:
            version = repo.get_pack_version(plan.version_id, plan.workspace_id)
        except PackVersionNotFoundError as exc:
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.VERSION_NOT_FOUND,
                "pack version not found in this workspace",
                details={"version_id": plan.version_id},
            ) from exc
        if str(version.status) != "draft":
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.VERSION_NOT_DRAFT,
                "the pack version is not a draft; published versions are immutable",
                details={"status": str(version.status)},
            )
        owned_asset_id = str(((receipt or {}).get("asset") or {}).get("asset_id") or "")
        target_asset_id: str | None = None
        source_asset = None
        present_keys: list[str] = []
        role_refs: list[dict[str, Any]] = []
        for asset in version.assets:
            present_keys.append(str(asset.pose_slot))
            if str(asset.pose_slot) == plan.reference_key:
                if owned_asset_id and str(asset.id) == owned_asset_id:
                    target_asset_id = str(asset.id)
                else:
                    raise ReferenceAssetJobError(
                        ReferenceAssetRefusalCode.TARGET_KEY_PRESENT,
                        "the target reference key already carries an asset",
                        details={"reference_key": plan.reference_key},
                    )
            if str(asset.pose_slot) == plan.source_reference_key:
                source_asset = asset
            view_part, role_part = str(asset.pose_slot).split("@", 1)
            del view_part
            if role_part != plan.role:
                continue
            from app.persistence.models import Artifact  # noqa: PLC0415

            row = session.get(Artifact, str(asset.artifact_id))
            role_refs.append(
                {
                    "key": str(asset.pose_slot),
                    "artifact_id": str(asset.artifact_id),
                    "sha256": str(getattr(row, "sha256", "") or ""),
                    "size_bytes": int(getattr(row, "size_bytes", 0) or 0),
                }
            )
        distinct: list[dict[str, Any]] = []
        seen: set[str] = set()
        for item in sorted(role_refs, key=lambda entry: (entry["key"] != plan.source_reference_key,
                                                         entry["key"])):
            if item["sha256"] and item["sha256"] not in seen:
                seen.add(item["sha256"])
                distinct.append(item)
        refs_min = sr.ENGINE_REFERENCE_MINIMA_PIN[sr.ENGINE_CAPABILITY_PINS[0]][1]
        if len(distinct) < refs_min:
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.REFERENCE_SET_INSUFFICIENT,
                f"capability {sr.ENGINE_CAPABILITY_PINS[0]} requires {refs_min} independent "
                f"reference artifacts for role {plan.role!r}; got {len(distinct)}",
                details={"reference_keys": sorted(present_keys), "distinct": len(distinct)},
            )
        if source_asset is None:
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.SOURCE_REFERENCE_MISSING,
                "the source identity reference is not attached to the version",
                details={
                    "source_reference_key": plan.source_reference_key,
                    "present": present_keys,
                },
            )
        try:
            _asset, path, _mime = repo.resolve_asset_content(
                character_id=plan.character_id,
                version_id=plan.version_id,
                asset_id=str(source_asset.id),
                workspace_id=plan.workspace_id,
            )
        except Exception as exc:  # typed refusals from the repository
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.SOURCE_REFERENCE_MISSING,
                f"source reference bytes are not serviceable: {type(exc).__name__}",
                details={"source_reference_key": plan.source_reference_key},
            ) from exc
        data = Path(path).read_bytes()
    actual = _sha256_bytes(data)
    if actual != plan.source_sha256:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.SOURCE_HASH_MISMATCH,
            "source reference bytes changed after the intent was registered",
            details={"expected": plan.source_sha256, "actual": actual},
        )
    return _LibraryState(
        source_path=Path(path),
        source_bytes=data,
        target_asset_id=target_asset_id,
        identity_refs=tuple(distinct),
    )


def _ingest_generated_asset(
    ctx: WorkerContext, plan: ReferenceAssetPlan, managed_root: Path, artifact_path: Path
) -> Any:
    """Save the generated bytes through the MF-END-03 managed ingest (draft only)."""
    from app.config import AppConfig  # noqa: PLC0415

    caps = AppConfig()
    written: list[str] = []
    with ctx.session_factory() as session:  # type: ignore[misc]
        repo = CharacterRepository(session, storage_root=managed_root)
        try:
            version = repo.get_pack_version(plan.version_id, plan.workspace_id)
        except PackVersionNotFoundError as exc:
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.VERSION_NOT_FOUND, "pack version vanished mid-run"
            ) from exc
        if str(version.status) != "draft":
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.VERSION_NOT_DRAFT,
                "the pack version became immutable before the asset could be saved",
                details={"status": str(version.status)},
            )
        try:
            with open(artifact_path, "rb") as fh:
                result = character_reference_ingest.ingest_reference_artwork(
                    session=session,
                    storage_root=managed_root,
                    workspace_id=plan.workspace_id,
                    version_id=plan.version_id,
                    reference_key=plan.reference_key,
                    filename=plan.output_filename,
                    stream=fh,
                    max_bytes=caps.max_image_upload_bytes,
                    max_dimension=caps.max_image_dimension,
                    max_pixels=caps.max_image_pixels,
                    purpose="artwork",
                    written=written,
                )
            session.commit()
        except PackVersionImmutableError as exc:
            session.rollback()
            character_reference_ingest.discard_written_files(managed_root, written)
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.VERSION_NOT_DRAFT,
                "the pack version is immutable; the generated asset was discarded",
            ) from exc
        except BaseException as exc:
            session.rollback()
            character_reference_ingest.discard_written_files(managed_root, written)
            if isinstance(exc, ReferenceAssetJobError):
                raise
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.INGEST_REFUSED,
                f"managed ingest refused the generated artwork: {type(exc).__name__}",
                details={"message": str(exc)[:400]},
            ) from exc
    return result


def _image_artifact(record: Any) -> Any:
    for artifact in record.output.artifacts:
        if str(getattr(artifact, "kind", "")) == "image":
            return artifact
    raise ReferenceAssetJobError(
        ReferenceAssetRefusalCode.ARTIFACT_MISSING,
        "the engine completed without an image artifact",
        details={"artifacts": [str(getattr(a, "kind", "")) for a in record.output.artifacts]},
    )


def _verify_artifact(managed_root: Path, artifact: Any) -> Path:
    rel = str(artifact.store_relative_path)
    path = ManagedRoot(managed_root).resolve(rel)
    if not path.is_file():
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.ARTIFACT_MISSING,
            "staged engine artifact is not on disk",
            details={"path": rel},
        )
    actual = hash_file(path)
    if actual != str(artifact.sha256):
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.ARTIFACT_HASH_MISMATCH,
            "staged engine artifact sha256 differs from the receipt",
            details={"path": rel, "expected": str(artifact.sha256), "actual": actual},
        )
    return path


def _result_payload(
    plan: ReferenceAssetPlan,
    *,
    receipt: dict[str, Any],
    generated: bool,
    replayed: bool,
) -> dict[str, Any]:
    asset = dict(receipt.get("asset") or {})
    engine = dict(receipt.get("engine") or {})
    return {
        "content_key": plan.content_key,
        "reference_key": plan.reference_key,
        "view": plan.view,
        "role": plan.role,
        "generated": generated,
        "replayed": replayed,
        "prompt_id": engine.get("prompt_id"),
        "asset_id": asset.get("asset_id"),
        "artifact_id": asset.get("artifact_id"),
        "sha256": asset.get("sha256"),
        "size_bytes": asset.get("size_bytes"),
        "status": str(receipt.get("status")),
        "receipt": receipt_relpath(plan.content_key),
    }


def _finalise(
    ctx: WorkerContext,
    plan: ReferenceAssetPlan,
    managed_root: Path,
    receipt: dict[str, Any],
    artifact: Any,
    *,
    generated: bool,
) -> dict[str, Any]:
    artifact_path = _verify_artifact(managed_root, artifact)
    ctx.progress(70.0, "saving generated artwork into the library")
    if ctx.is_cancelled():
        _update_receipt(managed_root, plan.content_key, status=RECEIPT_CANCELLED)
        return {"cancelled": True, "content_key": plan.content_key, "status": RECEIPT_CANCELLED}
    ingest = _ingest_generated_asset(ctx, plan, managed_root, artifact_path)
    receipt = _update_receipt(
        managed_root,
        plan.content_key,
        status=RECEIPT_COMPLETED,
        patch={
            "engine": {
                "prompt_id": str(receipt.get("engine", {}).get("prompt_id") or ""),
                "workflow_hash": receipt.get("engine", {}).get("workflow_hash"),
                "artifact_store_relative_path": str(artifact.store_relative_path),
                "artifact_sha256": str(artifact.sha256),
                "artifact_size_bytes": int(artifact.size_bytes),
            },
            "asset": {
                "asset_id": str(ingest.asset_id),
                "artifact_id": str(ingest.artifact_id),
                "sha256": str(ingest.sha256),
                "size_bytes": int(ingest.size_bytes),
                "mime_type": str(ingest.mime_type),
                "store_path": str(ingest.asset_id),
            },
        },
    )
    ctx.progress(100.0, "reference asset saved to the library")
    return _result_payload(plan, receipt=receipt, generated=generated, replayed=not generated)


def _generate_fresh(
    ctx: WorkerContext, plan: ReferenceAssetPlan, managed_root: Path, state: _LibraryState
) -> dict[str, Any]:
    ctx.progress(8.0, "staging the identity reference for the engine input dir")
    stage_reference_input(managed_root, plan, state.source_bytes)
    attempt_id = f"{ctx.job_id}:{ctx.attempt}"
    receipt: dict[str, Any] = {
        "content_key": plan.content_key,
        "status": RECEIPT_SUBMITTED,
        "attempt_id": attempt_id,
        "job_id": ctx.job_id,
        "attempt": int(ctx.attempt),
        "reference_key": plan.reference_key,
        "view": plan.view,
        "role": plan.role,
        "version_id": plan.version_id,
        "character_id": plan.character_id,
        "workspace_id": plan.workspace_id,
        "source_sha256": plan.source_sha256,
        "graph_file_sha256": plan.graph_file_sha256,
        "graph_config_hash": plan.graph_config_hash,
        "engine": {},
        "asset": {},
    }
    write_receipt(managed_root, receipt)
    if ctx.is_cancelled():
        _update_receipt(managed_root, plan.content_key, status=RECEIPT_CANCELLED)
        return {"cancelled": True, "content_key": plan.content_key, "status": RECEIPT_CANCELLED}
    ctx.progress(20.0, "submitting the reference-asset graph to the pinned engine")
    record, info = _drive_engine(
        plan,
        attempt_id=attempt_id,
        job_id=ctx.job_id,
        managed_root=managed_root,
        replay=False,
        references=state.identity_refs,
    )
    if str(getattr(record, "outcome", "")) != "completed":
        error = getattr(record, "error", None)
        _update_receipt(
            managed_root,
            plan.content_key,
            status=RECEIPT_FAILED,
            patch={"engine": {"prompt_id": None, "error": str(error)[:400] if error else None}},
        )
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.ENGINE_REFUSED,
            "the engine returned a failed attempt record",
            details={"outcome": str(getattr(record, "outcome", "")), "info": info},
        )
    artifact = _image_artifact(record)
    receipt = read_receipt(managed_root, plan.content_key) or receipt
    receipt["engine"] = {
        "prompt_id": str(record.output.prompt_id),
        "workflow_hash": str(record.output.graph_sha256_server),
        "attempt_id": attempt_id,
    }
    write_receipt(managed_root, receipt)
    return _finalise(ctx, plan, managed_root, receipt, artifact, generated=True)


def _replay_completed(
    ctx: WorkerContext,
    plan: ReferenceAssetPlan,
    managed_root: Path,
    receipt: dict[str, Any],
    state: _LibraryState,
) -> dict[str, Any]:
    """A terminal receipt: reuse the staged artifact, never re-generate."""
    if str(receipt.get("graph_config_hash") or "") != plan.graph_config_hash:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.CONTENT_KEY_MISMATCH,
            "receipt was produced by a different graph configuration",
        )
    engine = dict(receipt.get("engine") or {})
    rel = str(engine.get("artifact_store_relative_path") or "")
    sha = str(engine.get("artifact_sha256") or "")
    if not rel or not sha:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.RECEIPT_INCOMPLETE,
            "completed receipt lacks engine artifact facts",
        )
    path = ManagedRoot(managed_root).resolve(rel)
    if not path.is_file():
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.ARTIFACT_MISSING,
            "the staged artifact of the completed receipt is gone",
            details={"path": rel},
        )
    if hash_file(path) != sha:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.ARTIFACT_HASH_MISMATCH,
            "the staged artifact of the completed receipt no longer matches its sha256",
            details={"path": rel},
        )
    if state.target_asset_id:
        replay = dict(receipt.get("replay") or {})
        replay["count"] = int(replay.get("count") or 0) + 1
        replay["last_job_id"] = ctx.job_id
        receipt = _update_receipt(
            managed_root, plan.content_key, status=RECEIPT_COMPLETED, patch={"replay": replay}
        )
        ctx.progress(100.0, "receipt replay: asset already in the library")
        return _result_payload(plan, receipt=receipt, generated=False, replayed=True)
    # Engine bytes exist but the library row is missing (crash between run and
    # ingest): re-run ONLY the managed ingest — still zero engine POSTs.
    ingest = _ingest_generated_asset(ctx, plan, managed_root, path)
    receipt = _update_receipt(
        managed_root,
        plan.content_key,
        status=RECEIPT_COMPLETED,
        patch={
            "asset": {
                "asset_id": str(ingest.asset_id),
                "artifact_id": str(ingest.artifact_id),
                "sha256": str(ingest.sha256),
                "size_bytes": int(ingest.size_bytes),
                "mime_type": str(ingest.mime_type),
                "store_path": str(ingest.asset_id),
            }
        },
    )
    return _result_payload(plan, receipt=receipt, generated=False, replayed=True)


def _recover_in_doubt(
    ctx: WorkerContext,
    plan: ReferenceAssetPlan,
    managed_root: Path,
    receipt: dict[str, Any],
    state: _LibraryState,
) -> dict[str, Any]:
    """A non-terminal receipt: replay the RECORDED attempt; never a blind POST."""
    recorded_attempt = str(receipt.get("attempt_id") or "")
    if not recorded_attempt:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.RECEIPT_INCOMPLETE,
            "non-terminal receipt carries no attempt identity",
        )
    try:
        record, info = _drive_engine(
            plan,
            attempt_id=recorded_attempt,
            job_id=str(receipt.get("job_id") or ctx.job_id),
            managed_root=managed_root,
            replay=True,
            references=state.identity_refs,
        )
    except ReferenceAssetJobError as exc:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.RECEIPT_IN_DOUBT,
            "the previous attempt is not provably terminal; refusing a second submit",
            details={"previous_attempt": recorded_attempt, "engine": exc.as_dict()},
        ) from exc
    if str(getattr(record, "outcome", "")) != "completed":
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.RECEIPT_IN_DOUBT,
            "the replayed attempt is not completed",
            details={"outcome": str(getattr(record, "outcome", "")), "info": info},
        )
    artifact = _image_artifact(record)
    receipt["engine"] = {
        "prompt_id": str(record.output.prompt_id),
        "workflow_hash": str(record.output.graph_sha256_server),
        "attempt_id": recorded_attempt,
        "replayed": True,
    }
    write_receipt(managed_root, receipt)
    return _finalise(ctx, plan, managed_root, receipt, artifact, generated=False)


def run_reference_asset_job(ctx: WorkerContext) -> dict[str, Any]:
    """Durable step handler: generate ONE missing view and save it to the library."""
    manifest = dict(ctx.input_manifest)
    managed_root = _manifest_managed_root(manifest)
    plan = reference_asset_plan(manifest)
    ctx.progress(2.0, "reference-asset plan resolved from the durable manifest")
    receipt = read_receipt(managed_root, plan.content_key)
    state = _assert_library_state(ctx, plan, managed_root, receipt)
    if receipt is None:
        return _generate_fresh(ctx, plan, managed_root, state)
    status = str(receipt.get("status") or "")
    if status == RECEIPT_COMPLETED:
        return _replay_completed(ctx, plan, managed_root, receipt, state)
    if status == RECEIPT_CANCELLED:
        _update_receipt(managed_root, plan.content_key, status=RECEIPT_SUBMITTED)
        return _recover_in_doubt(ctx, plan, managed_root, receipt, state)
    return _recover_in_doubt(ctx, plan, managed_root, receipt, state)


def validate_reference_asset_outputs(
    ctx: WorkerContext, result: dict[str, Any], staging_dir: Path
) -> dict[str, Any]:
    """Register-time fail-closed gate: receipt + library asset must be on disk."""
    del staging_dir  # the job publishes under the managed root, not the staging dir
    if result.get("cancelled"):
        return {"cancelled": True}
    content_key = str(result.get("content_key") or "")
    if not content_key:
        raise JobError("reference-asset result carries no content key")
    managed_root = _manifest_managed_root(dict(ctx.input_manifest))
    receipt = read_receipt(managed_root, content_key)
    if receipt is None or str(receipt.get("status")) != RECEIPT_COMPLETED:
        raise JobError(f"reference-asset receipt for {content_key} is not completed")
    engine = dict(receipt.get("engine") or {})
    rel = str(engine.get("artifact_store_relative_path") or "")
    sha = str(engine.get("artifact_sha256") or "")
    path = ManagedRoot(managed_root).resolve(rel)
    if not path.is_file() or hash_file(path) != sha:
        raise JobError(f"reference-asset artifact {rel} is missing or has drifted")
    return {
        "receipt": {"relative_path": receipt_relpath(content_key), "sha256": hash_file(
            receipt_path(managed_root, content_key)
        )},
        "engine_artifact": {"relative_path": rel, "sha256": sha},
        "asset_id": (receipt.get("asset") or {}).get("asset_id"),
    }


