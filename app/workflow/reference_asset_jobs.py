class ReferenceAssetJobError(Exception):  # noqa: N818 — mirrors the refusal naming family
    """Typed refusal raised by the reference-asset job module."""

    def __init__(
        self,
        code: ReferenceAssetRefusalCode,
        detail: str,
        *,
        details: dict[str, Any] | None = None,
        retryable: bool = False,
    ) -> None:
        super().__init__(f"{code.value}: {detail}")
        self.code = code
        self.detail = detail
        self.details = dict(details or {})
        self.retryable = retryable

    def as_dict(self) -> dict[str, Any]:
        out: dict[str, Any] = {"code": self.code.value, "detail": self.detail}
        if self.details:
            out["details"] = dict(self.details)
        if self.retryable:
            out["retryable"] = True
        return out


# ── small helpers ────────────────────────────────────────────────────────────


def _sha256_bytes(data: bytes) -> str:
    return hashlib.sha256(data).hexdigest()


def _repo_root() -> Path:
    return Path(__file__).resolve().parents[2]


def _canonical_json(payload: Any) -> bytes:
    return json.dumps(payload, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode(
        "utf-8"
    )


def _manifest_managed_root(manifest: dict[str, Any]) -> Path:
    raw = str(manifest.get("managed_root") or "").strip()
    if not raw:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.REQUEST_INVALID, "input_manifest carries no managed_root"
        )
    root = Path(raw)
    if not root.is_absolute():
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.REQUEST_INVALID, "managed_root must be absolute"
        )
    return root


def load_graph_documents() -> tuple[dict[str, Any], dict[str, Any]]:
    """Load the frozen graph document + manifest, pinning the file sha256.

    Returns ``(graph_document, manifest)`` where the graph file sha256 equals
    ``manifest["workflow"]["graph_file_sha256"]`` — any other bytes refuse.
    """
    root = _repo_root()
    graph_path = root / GRAPH_FILE_REL
    manifest_path = root / GRAPH_MANIFEST_REL
    try:
        graph_bytes = graph_path.read_bytes()
        manifest = json.loads(manifest_path.read_text(encoding="utf-8"))
    except (OSError, ValueError) as exc:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.GRAPH_PIN_MISMATCH,
            f"frozen graph document unreadable: {type(exc).__name__}:{exc}",
            details={"graph_file": GRAPH_FILE_REL},
        ) from exc
    declared = str(((manifest or {}).get("workflow") or {}).get("graph_file_sha256") or "")
    actual = _sha256_bytes(graph_bytes)
    if not declared or declared != actual:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.GRAPH_PIN_MISMATCH,
            "graph file sha256 differs from the frozen manifest pin",
            details={"declared": declared, "actual": actual},
        )
    try:
        document = json.loads(graph_bytes.decode("utf-8"))
    except ValueError as exc:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.GRAPH_PIN_MISMATCH, f"graph document is not JSON: {exc}"
        ) from exc
    if str(document.get("schema_version")) != GRAPH_SCHEMA_VERSION:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.GRAPH_PIN_MISMATCH,
            "graph document declares an unknown schema_version",
            details={"schema_version": document.get("schema_version")},
        )
    if not isinstance(document.get("graph"), dict) or not document["graph"]:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.GRAPH_PIN_MISMATCH,
            "graph document carries no API-format graph object",
        )
    return document, manifest


def parse_target_key(reference_key: str) -> tuple[str, str]:
    """Validate ``<view>@<role>`` with the FROZEN MF-END-03 grammar."""
    try:
        view, role = character_reference_ingest.validate_reference_key(reference_key)
    except Exception as exc:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.TARGET_KEY_INVALID,
            f"reference key refused: {exc}",
            details={"reference_key": reference_key},
        ) from exc
    return view, role


def _seed_for(version_id: str, reference_key: str, source_sha256: str) -> int:
    digest = hashlib.sha256(f"{version_id}:{reference_key}:{source_sha256}".encode())
    return int(digest.hexdigest()[:15], 16) % SEED_CEILING


def _config_hash(
    *,
    canvas_width: int,
    canvas_height: int,
    ref_longer_side: int,
    neutral_rgb_int: int,
    seed: int,
    filename_prefix: str,
) -> str:
    return "sha256:" + _sha256_bytes(
        _canonical_json(
            {
                "canvas": [canvas_width, canvas_height],
                "cfg": CFG,
                "filename_prefix": filename_prefix,
                "neutral_rgb_int": neutral_rgb_int,
                "ref_longer_side": ref_longer_side,
                "seed": seed,
                "steps": STEPS,
            }
        )
    )


def content_key_for(fields: dict[str, Any]) -> str:
    """Canonical content key over the identity/view/style/graph-fingerprint fields."""
    return "sha256:" + _sha256_bytes(_canonical_json(fields))


