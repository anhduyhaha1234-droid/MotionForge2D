def _drive_engine(
    plan: ReferenceAssetPlan,
    *,
    attempt_id: str,
    job_id: str,
    managed_root: Path,
    replay: bool,
    references: Any = None,
) -> tuple[Any, dict[str, Any]]:
    """One attempt through the shared engine; replay reuses durable evidence."""
    from app.adapters.media_engine.comfy import ComfyEngineRefusal  # noqa: PLC0415

    pinning = _load_pinning()
    workflow_hash = str(pinning.hash_workflow(plan.graph))
    binding = build_engine_binding(
        plan,
        attempt_id=attempt_id,
        job_id=job_id,
        workflow_hash=workflow_hash,
        references=references,
    )
    engine = _ENGINE_FACTORY(managed_root)
    kwargs: dict[str, Any] = {
        "graph": plan.graph,
        "terminal_outputs": {SAVE_NODE_ID: {"kind": "image", "media_type": "image"}},
        "shot_id": f"reference_asset:{plan.reference_key}",
        "params": None,
        "decoded_facts": sr.EngineDecodedFacts(
            decoded_frames=1, first_pts_ticks=0, timebase="1/1", mapping=None
        ),
    }
    try:
        if replay:
            record, info = engine.replay(binding, **kwargs)
        else:
            record = engine.run_shot(binding, **kwargs)
            info = {"replayed": False}
    except ComfyEngineRefusal as exc:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.ENGINE_REFUSED,
            f"engine refused the attempt: {exc.code.value}",
            details={"engine": exc.as_dict()},
            retryable=bool(getattr(exc, "retryable", False)),
        ) from exc
    finally:
        with contextlib.suppress(Exception):
            engine.close()
    return record, dict(info)


