def build_reference_asset_graph(
    template_graph: dict[str, Any],
    *,
    ref_filename: str,
    prompt: str,
    seed: int,
    filename_prefix: str,
    canvas_width: int = CANVAS_WIDTH,
    canvas_height: int = CANVAS_HEIGHT,
    ref_longer_side: int = REF_LONGER_SIDE,
    neutral_rgb_int: int = NEUTRAL_RGB_INT,
) -> dict[str, Any]:
    """Deep-copy the frozen graph and apply the documented parameter overrides."""
    if not ref_filename or Path(ref_filename).name != ref_filename:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.REQUEST_INVALID,
            "ref_filename must be a bare file name (no directories)",
            details={"ref_filename": ref_filename},
        )
    if not ref_filename.lower().endswith(".png"):
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.REQUEST_INVALID, "ref_filename must be a PNG file name"
        )
    if not prompt.strip():
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.VIEW_PROMPT_REFUSED, "view prompt must be non-empty"
        )
    if not 0 <= int(seed) < SEED_CEILING:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.REQUEST_INVALID, "seed must be within [0, 2**63)"
        )
    if canvas_width % 16 or canvas_height % 16 or not (
        16 <= canvas_width <= 16384 and 16 <= canvas_height <= 16384
    ):
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.REQUEST_INVALID,
            "canvas dimensions must be 16..16384 and divisible by 16",
            details={"canvas": [canvas_width, canvas_height]},
        )
    if not 16 <= int(ref_longer_side) <= 4096:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.REQUEST_INVALID, "ref_longer_side must be within 16..4096"
        )
    if not 0 <= int(neutral_rgb_int) <= 0xFFFFFF:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.REQUEST_INVALID, "neutral_rgb_int must be within 0..0xFFFFFF"
        )
    graph = json.loads(json.dumps(template_graph))
    overrides: tuple[tuple[str, str, Any], ...] = (
        ("REF_LOAD", "image", ref_filename),
        ("PROMPT", "text", prompt),
        ("REF_RESIZE", "resize_type.longer_size", int(ref_longer_side)),
        ("REF_BG", "color", int(neutral_rgb_int)),
        ("NOISE", "noise_seed", int(seed)),
        ("LATENT", "width", int(canvas_width)),
        ("LATENT", "height", int(canvas_height)),
        ("SIGMAS", "steps", STEPS),
        ("SIGMAS", "width", int(canvas_width)),
        ("SIGMAS", "height", int(canvas_height)),
        ("GUIDER", "cfg", CFG),
        ("SAVE", "filename_prefix", filename_prefix),
    )
    for node_id, input_name, value in overrides:
        node = graph.get(node_id)
        if not isinstance(node, dict) or not isinstance(node.get("inputs"), dict):
            raise ReferenceAssetJobError(
                ReferenceAssetRefusalCode.GRAPH_PIN_MISMATCH,
                "frozen graph is missing a node the parameter table pins",
                details={"node": node_id},
            )
        node["inputs"][input_name] = value
    return graph


def reference_asset_plan(manifest: dict[str, Any]) -> ReferenceAssetPlan:
    """Recompute the plan (and content key) from a durable input manifest.

    Every field is validated here; a manifest whose recomputed content key
    differs from the recorded one refuses (``content_key_mismatch``).
    """
    required = (
        "workspace_id",
        "character_id",
        "version_id",
        "reference_key",
        "source_reference_key",
        "source_artifact_id",
        "source_sha256",
        "source_size_bytes",
        "view_prompt",
    )
    missing = [name for name in required if not str(manifest.get(name) or "").strip()]
    if missing:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.REQUEST_INVALID,
            "input_manifest is missing required fields",
            details={"missing": missing},
        )
    reference_key = str(manifest["reference_key"])
    source_reference_key = str(manifest["source_reference_key"])
    view, role = parse_target_key(reference_key)
    if source_reference_key == reference_key:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.REQUEST_INVALID,
            "source and target reference keys are identical",
            details={"reference_key": reference_key},
        )
    prompt = str(manifest["view_prompt"]).strip()
    if view.lower() not in prompt.lower():
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.VIEW_PROMPT_REFUSED,
            "view prompt must name the target view",
            details={"view": view},
        )
    document, _manifest = load_graph_documents()
    graph_file_sha256 = str(
        (_manifest.get("workflow") or {}).get("graph_file_sha256") or ""
    )
    seed = manifest.get("seed")
    if seed is None:
        seed = _seed_for(str(manifest["version_id"]), reference_key, str(manifest["source_sha256"]))
    seed = int(seed)
    canvas_width = int(manifest.get("canvas_width", CANVAS_WIDTH))
    canvas_height = int(manifest.get("canvas_height", CANVAS_HEIGHT))
    ref_longer_side = int(manifest.get("ref_longer_side", REF_LONGER_SIDE))
    neutral_rgb_int = int(manifest.get("neutral_rgb_int", NEUTRAL_RGB_INT))
    filename_prefix = str(
        manifest.get("filename_prefix") or f"mf_reference_asset_v1/{view}_{role}"
    )
    output_filename = str(
        manifest.get("output_filename") or f"end09_{view}_{role}_{str(seed)[:10]}.png"
    )
    staged_filename = f"end09_ref_{str(manifest['source_sha256'])[:16]}.png"
    graph = build_reference_asset_graph(
        document["graph"],
        ref_filename=staged_filename,
        prompt=prompt,
        seed=seed,
        filename_prefix=filename_prefix,
        canvas_width=canvas_width,
        canvas_height=canvas_height,
        ref_longer_side=ref_longer_side,
        neutral_rgb_int=neutral_rgb_int,
    )
    style_version = manifest.get("style_version")
    graph_config_hash = _config_hash(
        canvas_width=canvas_width,
        canvas_height=canvas_height,
        ref_longer_side=ref_longer_side,
        neutral_rgb_int=neutral_rgb_int,
        seed=seed,
        filename_prefix=filename_prefix,
    )
    fields = {
        "schema": RECEIPT_SCHEMA,
        "workspace_id": str(manifest["workspace_id"]),
        "character_id": str(manifest["character_id"]),
        "version_id": str(manifest["version_id"]),
        "reference_key": reference_key,
        "source_reference_key": source_reference_key,
        "source_sha256": str(manifest["source_sha256"]),
        "style_version": None if style_version is None else str(style_version),
        "graph_file_sha256": graph_file_sha256,
        "graph_config_hash": graph_config_hash,
        "view_prompt_sha256": _sha256_bytes(prompt.encode("utf-8")),
    }
    key = reference_asset_content_key(fields)
    recorded = str(manifest.get("content_key") or "")
    if recorded and recorded != key:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.CONTENT_KEY_MISMATCH,
            "manifest content key does not match the recomputed identity",
            details={"recorded": recorded, "recomputed": key},
        )
    return ReferenceAssetPlan(
        workspace_id=str(manifest["workspace_id"]),
        character_id=str(manifest["character_id"]),
        version_id=str(manifest["version_id"]),
        reference_key=reference_key,
        view=view,
        role=role,
        source_reference_key=source_reference_key,
        source_artifact_id=str(manifest["source_artifact_id"]),
        source_sha256=str(manifest["source_sha256"]),
        source_size_bytes=int(manifest["source_size_bytes"]),
        style_version=None if style_version is None else str(style_version),
        view_prompt=prompt,
        seed=seed,
        canvas_width=canvas_width,
        canvas_height=canvas_height,
        ref_longer_side=ref_longer_side,
        neutral_rgb_int=neutral_rgb_int,
        filename_prefix=filename_prefix,
        output_filename=output_filename,
        graph_file_sha256=graph_file_sha256,
        graph_config_hash=graph_config_hash,
        graph=graph,
        content_key=key,
        graph_object=document,
        graph_models=tuple(
            entry for entry in (_manifest.get("models") or []) if isinstance(entry, dict)
        ),
    )


def reference_asset_content_key(fields: dict[str, Any]) -> str:
    """Canonical content key for the identity/view/style/graph fingerprint."""
    return content_key_for(dict(fields))


# ── receipts (durable, beside the managed artifacts) ─────────────────────────


def receipt_relpath(content_key: str) -> str:
    digest = content_key.split(":", 1)[-1]
    return f"{RECEIPT_DIR}/{digest[:2]}/{digest}.json"


def receipt_path(managed_root: Path, content_key: str) -> Path:
    rel = receipt_relpath(content_key)
    return ManagedRoot(managed_root).resolve(rel)


def read_receipt(managed_root: Path, content_key: str) -> dict[str, Any] | None:
    path = receipt_path(managed_root, content_key)
    if not path.is_file():
        return None
    try:
        payload = parse_json(path.read_text(encoding="utf-8"), None)
    except OSError as exc:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.RECEIPT_INCOMPLETE,
            f"receipt unreadable: {type(exc).__name__}",
            details={"receipt": receipt_relpath(content_key)},
        ) from exc
    if not isinstance(payload, dict) or payload.get("schema") != RECEIPT_SCHEMA:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.RECEIPT_INCOMPLETE,
            "receipt does not declare the expected schema",
            details={"receipt": receipt_relpath(content_key)},
        )
    return payload


def write_receipt(managed_root: Path, receipt: dict[str, Any]) -> Path:
    """Atomically write the receipt; never downgrade a completed one."""
    content_key = str(receipt.get("content_key") or "")
    if not content_key:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.RECEIPT_INCOMPLETE, "receipt carries no content_key"
        )
    payload = dict(receipt)
    payload["schema"] = RECEIPT_SCHEMA
    path = receipt_path(managed_root, content_key)
    existing = read_receipt(managed_root, content_key)
    if (
        existing is not None
        and existing.get("status") == RECEIPT_COMPLETED
        and payload.get("status") != RECEIPT_COMPLETED
    ):
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.RECEIPT_INCOMPLETE,
            "refusing to downgrade a completed receipt",
            details={"receipt": receipt_relpath(content_key)},
        )
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + f".tmp{uuid.uuid4().hex[:8]}")
    tmp.write_text(json.dumps(payload, indent=2, sort_keys=True) + "\n", encoding="utf-8")
    os.replace(tmp, path)
    return path


def _update_receipt(
    managed_root: Path, content_key: str, *, status: str, patch: dict[str, Any] | None = None
) -> dict[str, Any]:
    current = read_receipt(managed_root, content_key)
    if current is None:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.RECEIPT_INCOMPLETE, "receipt is not on disk"
        )
    current["status"] = status
    if patch:
        current.update(patch)
    write_receipt(managed_root, current)
    return current


