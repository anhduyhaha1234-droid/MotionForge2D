def stage_reference_input(managed_root: Path, plan: ReferenceAssetPlan, data: bytes) -> Path:
    """Write the identity reference bytes into the staged-input directory."""
    actual = _sha256_bytes(data)
    if actual != plan.source_sha256:
        raise ReferenceAssetJobError(
            ReferenceAssetRefusalCode.SOURCE_HASH_MISMATCH,
            "source reference bytes do not match the manifest sha256",
            details={"expected": plan.source_sha256, "actual": actual},
        )
    target = runtime_input_dir(managed_root) / f"end09_ref_{plan.source_sha256[:16]}.png"
    target.parent.mkdir(parents=True, exist_ok=True)
