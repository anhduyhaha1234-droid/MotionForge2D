def _run_job(worker: DurableWorker) -> None:
    worker.run_once()


def _job_state(session_factory, job_id: str) -> str:
    with session_factory() as s:
        return JobRepository(s).get_job(job_id).state


def _chain_jobs(session_factory, video_item_id: str) -> list[Job]:
    with session_factory() as s:
        return list(
            s.scalars(
                select(Job)
                .where(
                    Job.owner_type == "video_item",
                    Job.owner_id == video_item_id,
                )
                .order_by(Job.created_at)
            ).all()
        )


def _scene_rows(session_factory, video_item_id: str) -> list[Scene]:
    with session_factory() as s:
        return list(
            s.scalars(
                select(Scene)
                .where(Scene.video_item_id == video_item_id)
                .order_by(Scene.position)
            ).all()
        )


def _staging_files(managed_root: Path) -> list[Path]:
    staging = managed_root / "staging"
    if not staging.is_dir():
        return []
    return [p for p in staging.rglob("*") if p.is_file()]


def _ready_video_artifacts(session_factory, workspace_id: str) -> list[Artifact]:
    with session_factory() as s:
        return list(
            s.scalars(
                select(Artifact)
                .where(
                    Artifact.workspace_id == workspace_id,
                    Artifact.kind == "video",
                    Artifact.state == "ready",
                )
                .order_by(Artifact.relative_path)
            ).all()
        )


def _artifact_sha_size(path: Path) -> tuple[str, int]:
    return hashlib.sha256(path.read_bytes()).hexdigest(), path.stat().st_size


def _owner_purposes(session_factory, artifact_id: str) -> set[str]:
    with session_factory() as s:
        return set(
            s.scalars(
                select(ArtifactOwner.purpose).where(ArtifactOwner.artifact_id == artifact_id)
            ).all()
        )


def _fast_orchestrator(
    session_factory, managed_root: Path, monkeypatch
) -> AnalyzeChainOrchestrator:
    """A fast-polling orchestrator injected as the route's accessor."""
    orch = AnalyzeChainOrchestrator(
        session_factory,
        managed_root,
        poll_interval=0.01,
    )
    monkeypatch.setattr(ao_module, "get_analyze_orchestrator", lambda: orch)
    return orch


def _drive_to_terminal(worker, session_factory, video_item_id: str, max_rounds: int = 20) -> None:
    """Worker + explicit orchestrator advancement (backend ownership) until
    the chain's scene job is terminal — repository reads only."""
    for _ in range(max_rounds):
        _run_job(worker)
        ao_module.get_analyze_orchestrator().advance_once()
        jobs = _chain_jobs(session_factory, video_item_id)
        if len(jobs) >= 3 and jobs[-1].state in ("completed", "failed", "cancelled"):
            return
    raise AssertionError("chain did not reach a terminal scene state")


def _db_snapshot(session_factory, managed_root: Path) -> dict:
    """Every durable row (as plain tuples) + every managed file path."""
    tables: dict[str, list] = {}
    models = (
        Job,
        JobStep,
        JobAttempt,
        JobEvent,
        JobLease,
        Artifact,
        ArtifactOwner,
        Scene,
        VideoItem,
        Project,
        Workspace,
    )
    with session_factory() as s:
        for model in models:
            rows = s.execute(select(model)).scalars().all()
            cols = list(model.__table__.columns.keys())
            tables[model.__name__] = sorted(tuple(getattr(r, c) for c in cols) for r in rows)
    files = sorted(str(p.relative_to(managed_root)) for p in managed_root.rglob("*") if p.is_file())
    return {"tables": tables, "files": files}


# ── AC: POST once, NO GET — chain completes under orchestrator+worker ───────


def test_post_once_no_get_chain_completes_under_orchestrator(
    worker, session_factory, managed_root, api_client, cfr_cut_video, monkeypatch
) -> None:
    """Exactly ONE POST /analyze; NO GET /analyze at all; the backend
    orchestration loop + durable worker complete T02→T03→T04."""
    pid = _create_project(api_client, "S05C02 no-get")
    _upload_video(api_client, pid, cfr_cut_video)

    orch = _fast_orchestrator(session_factory, managed_root, monkeypatch)
    try:
        resp = api_client.post(
            f"/api/projects/{pid}/analyze",
            json={"generation": "1", "title": "no-get"},
        )
        assert resp.status_code == 200, resp.text
        state = resp.json()
        import_job_id = state["steps"]["import"]["job_id"]
        assert import_job_id is not None
        assert state["steps"]["proxy"]["status"] == "not_created"
        assert state["steps"]["scene_detect"]["status"] == "not_created"
        assert state["source_sha256"] == hashlib.sha256(cfr_cut_video.read_bytes()).hexdigest()

        # NO GET /analyze from here on.  The orchestrator's background loop
        # (started by the POST) advances the chain; the worker executes.
        deadline = time.monotonic() + 90
        while time.monotonic() < deadline:
            _run_job(worker)
            with session_factory() as s:
                jobs = list(
                    s.scalars(
                        select(Job)
                        .where(Job.owner_type == "video_item")
                        .order_by(Job.created_at)
                    ).all()
                )
            if len(jobs) >= 3:
                last = jobs[-1]
                if last.state in ("completed", "failed", "cancelled"):
                    break
            time.sleep(0.02)
        else:
            raise AssertionError("chain did not complete under the orchestrator loop")

        jobs = _chain_jobs(session_factory, state["video_item_id"])
        assert [j.job_type for j in jobs] == [
            video_import.JOB_TYPE_ANALYZE_MEDIA,
            video_proxy.JOB_TYPE_GENERATE_PROXY,
            video_import.JOB_TYPE_ANALYZE_MEDIA,
        ]
        assert [j.state for j in jobs] == ["completed", "completed", "completed"]
        assert _scene_rows(session_factory, state["video_item_id"]) != []
        assert _staging_files(managed_root) == []
    finally:
        orch.stop(timeout=2.0)


# ── AC: API process restart after import and after proxy ────────────────────


def test_api_restart_after_import_and_after_proxy_chain_completes(
    worker, session_factory, db_path, managed_root, api_client, cfr_cut_video, monkeypatch
) -> None:
    """The API process restarts after import and after proxy (fresh
    engines, workers AND orchestrators over the same database file); the
    chain completes with exactly one effect set per step."""
    pid = _create_project(api_client, "S05C02 restart")
    _upload_video(api_client, pid, cfr_cut_video)
    orch1 = _fast_orchestrator(session_factory, managed_root, monkeypatch)

    state = _submit_chain(api_client, pid, cfr_cut_video.name)
    import_job_id = state["steps"]["import"]["job_id"]
    orch1.stop(timeout=2.0)  # deterministic explicit advancement from here

    # Process 1: import completes.
    _run_job(worker)
    assert _job_state(session_factory, import_job_id) == "completed"
    orch1.advance_once()
    jobs = _chain_jobs(session_factory, state["video_item_id"])
    assert len(jobs) == 2
    proxy_job_id = jobs[1].id

    # "API process restart" after import: fresh engine + worker +
    # orchestrator on the same DB file.
    factory2 = create_session_factory(create_engine_for_path(db_path))
    w2 = DurableWorker(
        factory2,
        config=WorkerConfig(
            worker_id="chain-progression-worker-2",
            lease_ttl=60,
            heartbeat_interval=15,
            poll_interval=0.01,
            max_attempts=3,
            staging_root=managed_root,
        ),
        clock=FakeClock(),
        sleeper=FakeSleeper(),
    )
    register_generate_proxy_handler(w2)
    register_scene_detection_handler(w2)
    orch2 = AnalyzeChainOrchestrator(factory2, managed_root)

    assert w2.run_once() == 1  # claims the queued proxy job
    assert _job_state(factory2, proxy_job_id) == "completed"
    orch2.advance_once()
    jobs = _chain_jobs(factory2, state["video_item_id"])
    assert len(jobs) == 3
    scene_job_id = jobs[2].id

    # "API process restart" after proxy: yet another fresh process.
    factory3 = create_session_factory(create_engine_for_path(db_path))
    w3 = DurableWorker(
        factory3,
        config=WorkerConfig(
            worker_id="chain-progression-worker-3",
            lease_ttl=60,
            heartbeat_interval=15,
            poll_interval=0.01,
            max_attempts=3,
            staging_root=managed_root,
        ),
        clock=FakeClock(),
        sleeper=FakeSleeper(),
    )
    register_scene_detection_handler(w3)
    orch3 = AnalyzeChainOrchestrator(factory3, managed_root)

    assert w3.run_once() == 1  # claims the queued scene job
    assert _job_state(factory3, scene_job_id) == "completed"
    orch3.advance_once()

    # Terminal: every chain job completed, exactly one effect set.
    assert [_job_state(factory3, j.id) for j in _chain_jobs(factory3, state["video_item_id"])] == [
        "completed",
        "completed",
        "completed",
    ]
    rows = _scene_rows(factory3, state["video_item_id"])
    assert len(rows) == 2
    arts = _ready_video_artifacts(factory3, "default")
    assert len(arts) == 2  # exactly one source + one proxy
    root = managed_root.resolve()
    for art in arts:
        sha, size = _artifact_sha_size(root / art.relative_path)
        assert (art.sha256, art.size_bytes) == (sha, size)
    with factory3() as s:
        assert len(JobRepository(s).list_attempts(proxy_job_id)) == 1
        assert len(JobRepository(s).list_attempts(scene_job_id)) == 1
    assert _staging_files(root) == []


# ── AC: GET repeated/concurrent → ZERO DB mutations ─────────────────────────


def test_get_repeated_and_concurrent_zero_db_mutations(
    worker, session_factory, managed_root, api_client, cfr_cut_video, monkeypatch
) -> None:
    """Repeated AND concurrent GET /analyze cause zero database mutations
    (job rows, steps, attempts, events, leases, artifacts, owners, scenes,
    video items, projects, managed files)."""
    pid = _create_project(api_client, "S05C02 get readonly")
    _upload_video(api_client, pid, cfr_cut_video)
    orch = _fast_orchestrator(session_factory, managed_root, monkeypatch)
    _submit_chain(api_client, pid, cfr_cut_video.name)
    orch.stop(timeout=2.0)
    with session_factory() as s:
        item_id = s.scalar(select(VideoItem.id).where(VideoItem.project_id == pid))
    assert item_id is not None
    _drive_to_terminal(worker, session_factory, item_id)

    before = _db_snapshot(session_factory, managed_root)
    assert _job_state(session_factory, _chain_jobs(session_factory, item_id)[0].id) == "completed"

    # Repeated GETs: 200 + byte-identical chain JSON every time.
    first_json = None
    for _ in range(25):
        resp = api_client.get(f"/api/projects/{pid}/analyze")
        assert resp.status_code == 200, resp.text
        payload = resp.json()
        if first_json is None:
            first_json = payload
        else:
            assert payload == first_json
    assert first_json["chain_status"] == "completed"

    # Concurrent GETs: 6 threads, barrier-synchronized.
    errors: list[Exception] = []
    results: list[dict] = []

    def hammer() -> None:
        barrier.wait(timeout=10)
        try:
            resp = api_client.get(f"/api/projects/{pid}/analyze")
            assert resp.status_code == 200, resp.text
            results.append(resp.json())
        except Exception as exc:  # noqa: BLE001 - collected
            errors.append(exc)

    barrier = threading.Barrier(6)
    threads = [threading.Thread(target=hammer) for _ in range(6)]
    for t in threads:
        t.start()
    for t in threads:
        t.join(timeout=30)
    assert errors == []
    assert len(results) == 6
    for payload in results:
        assert payload == first_json

    after = _db_snapshot(session_factory, managed_root)
    assert after == before

    # GET on a NEVER-submitted project creates nothing (no durable shell).
    pid2 = _create_project(api_client, "S05C02 idle get")
