# ── AC: failure/cancel successor retry stays idempotent ─────────────────────


def test_failure_successor_retry_idempotent(
    worker, session_factory, managed_root, api_client, cfr_cut_video, monkeypatch
) -> None:
    """A failed scene step is retried via the orchestrator's successor
    path; duplicate retries reuse the same successor (contract §8.5)."""
    pid = _create_project(api_client, "S05C02 retry failed")
    _upload_video(api_client, pid, cfr_cut_video)
    orch = _fast_orchestrator(session_factory, managed_root, monkeypatch)
    state = _submit_chain(api_client, pid, cfr_cut_video.name)
    orch.stop(timeout=2.0)
    item_id = state["video_item_id"]

    _run_job(worker)  # import
    orch.advance_once()
    _run_job(worker)  # proxy
    orch.advance_once()
    jobs = _chain_jobs(session_factory, item_id)
    scene_job_id = jobs[2].id

    def fail_detect(ctx, input_path, profile, timebase):
        raise scene_detector.SceneDetectorError(
            CODE_SCENE_DETECT_FAILED, "injected detection failure"
        )

    monkeypatch.setattr(scene_detector, "_run_scene_detect", fail_detect)
    _run_job(worker)
    monkeypatch.undo()
    assert _job_state(session_factory, scene_job_id) == "failed"

    # Successor retry via the orchestrator (the retry endpoint's surface).
    retry1 = ao_module.get_analyze_orchestrator().retry_chain(pid)
    assert retry1 is not None
    successor_id = retry1["steps"]["scene_detect"]["job_id"]
    assert successor_id != scene_job_id
    assert retry1["steps"]["scene_detect"]["predecessor_job_id"] == scene_job_id
    assert _job_state(session_factory, scene_job_id) == "failed"  # immutable

    # Duplicate retries reuse the successor — never a 409/500.
    retry2 = ao_module.get_analyze_orchestrator().retry_chain(pid)
    assert retry2 is not None
    assert retry2["steps"]["scene_detect"]["job_id"] == successor_id
    retry3 = ao_module.get_analyze_orchestrator().retry_chain(pid)
    assert retry3 is not None
    assert retry3["steps"]["scene_detect"]["job_id"] == successor_id

    # The successor completes with exactly one effect set.
    _run_job(worker)
    assert _job_state(session_factory, successor_id) == "completed"
    rows = _scene_rows(session_factory, item_id)
    assert len(rows) == 2
    assert all(r.revision == 1 for r in rows)
    assert _staging_files(managed_root) == []


